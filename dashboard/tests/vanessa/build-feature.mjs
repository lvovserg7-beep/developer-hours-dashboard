function block(code) {
  return ['    """bsl', ...code.split("\n").map((line) => (line ? `    ${line}` : "")), '    """'].join("\n");
}

function serverCode(items) {
  const adds = items
    .map(([article, rate]) => `Артикулы.Добавить("${article}");\nРасходы.Добавить(${rate});`)
    .join("\n");
  return `Артикулы = Новый Массив;
Расходы = Новый Массив;
${adds}
Состав = Новый ТаблицаЗначений;
Состав.Колонки.Добавить("Номенклатура", Новый ОписаниеТипов("СправочникСсылка.Номенклатура"));
Состав.Колонки.Добавить("СуточныйРасход", Новый ОписаниеТипов("Число", Новый КвалификаторыЧисла(12, 2)));
Для Инд = 0 По Артикулы.ВГраница() Цикл
    Ном = Справочники.Номенклатура.НайтиПоРеквизиту("Артикул", Артикулы[Инд]);
    Если Не ЗначениеЗаполнено(Ном) Тогда
        ВызватьИсключение "Не найдена номенклатура с артикулом " + Артикулы[Инд];
    КонецЕсли;
    СтрокаСостава = Состав.Добавить();
    СтрокаСостава.Номенклатура = Ном;
    СтрокаСостава.СуточныйРасход = Расходы[Инд];
КонецЦикла;
Запрос = Новый Запрос;
Запрос.Текст = Alsn_ТекстыЗапросов.ТекстЗапросаСформироватьНаСервереМакет();
Запрос.УстановитьПараметр("ГоризонтПланирования", 10);
Запрос.УстановитьПараметр("НоменклатураДляРассчета", Состав);
Таблица1 = Запрос.Выполнить().Выгрузить();
Если Таблица1.Количество() = 0 Тогда
    ВызватьИсключение "Первая таблица пустая";
КонецЕсли;
Для Каждого СтрокаСостава Из Состав Цикл
    Найдено = Ложь;
    Для Каждого Строка Из Таблица1 Цикл
        Если Строка.Номенклатура <> СтрокаСостава.Номенклатура Тогда
            Продолжить;
        КонецЕсли;
        Найдено = Истина;
        Дельта = Строка.Требуется - Строка.ДневнойРасход * 10;
        Если Дельта < 0 Тогда
            Дельта = -Дельта;
        КонецЕсли;
        Если Дельта > 0.02 Тогда
            ВызватьИсключение "Требуется не сходится у " + Строка.Номенклатура;
        КонецЕсли;
        Ожидание = Строка.Требуется - Строка.ВНаличииОстаток + Строка.ЗаказаноОстаток;
        Дельта = Строка.КоличествоДляРасчета - Ожидание;
        Если Дельта < 0 Тогда
            Дельта = -Дельта;
        КонецЕсли;
        Если Дельта > 0.02 Тогда
            ВызватьИсключение "Количество для расчёта не сходится у " + Строка.Номенклатура;
        КонецЕсли;
    КонецЦикла;
    Если Не Найдено Тогда
        ВызватьИсключение "В первой таблице нет " + СтрокаСостава.Номенклатура;
    КонецЕсли;
КонецЦикла;
ТаблицаЗаказа = Новый ТаблицаЗначений;
ТаблицаЗаказа.Колонки.Добавить("Номенклатура", Новый ОписаниеТипов("СправочникСсылка.Номенклатура"));
ТаблицаЗаказа.Колонки.Добавить("Потребность", Новый ОписаниеТипов("Число", Новый КвалификаторыЧисла(15, 3)));
ТаблицаЗаказа.Колонки.Добавить("ВЗаказ", Новый ОписаниеТипов("Число", Новый КвалификаторыЧисла(15, 3)));
Запрос2 = Новый Запрос;
Запрос2.Текст = Alsn_ТекстыЗапросов.ТекстЗапросаСформироватьНаСервереМакет2();
Запрос2.УстановитьПараметр("ВыборкаПотребности", Таблица1);
Запрос2.УстановитьПараметр("ВЗаказ", ТаблицаЗаказа);
Таблица2 = Запрос2.Выполнить().Выгрузить();
Живых = 0;
Для Каждого Строка Из Таблица2 Цикл
    Если Не ЗначениеЗаполнено(Строка.Номенклатура) Тогда
        Продолжить;
    КонецЕсли;
    Живых = Живых + 1;
    Ожидание = Строка.КоличествоПотребность - Строка.Заказано - Строка.ВНаличииОстаток - Строка.Заказ;
    Дельта = Строка.КЗаказу - Ожидание;
    Если Дельта < 0 Тогда
        Дельта = -Дельта;
    КонецЕсли;
    Если Дельта > 0.05 Тогда
        ВызватьИсключение "К заказу не сходится у " + Строка.Номенклатура;
    КонецЕсли;
КонецЦикла;
Если Живых = 0 Тогда
    ВызватьИсключение "Вторая таблица без комплектующих";
КонецЕсли;`;
}

